"use client";

import study from "@/lib/autopilot/study-results.json";
import type { RiskProfile } from "@/lib/autopilot/types";
import { Panel, Stat } from "@/components/fd/primitives";
import { monthYearUtc, signedPct } from "./format";

interface ProfileStats {
  sessions: number;
  positivePct: number;
  medianPct: number;
  p10Pct: number;
  p90Pct: number;
  worstPct: number;
  bestPct: number;
  killSwitchPct: number;
  reachedDoublePct: number;
}

const PROFILES = study.profiles as unknown as Record<RiskProfile, ProfileStats>;
const tone = (n: number) => (n >= 0 ? "gain" : "loss") as "gain" | "loss";

/**
 * What the production engine actually did over every 90-day window in four
 * years of real candles. Numbers come from study-results.json, regenerated by
 * `AUTOPILOT_STUDY=1 npx vitest run src/lib/autopilot/study.test.ts`.
 */
export function HistoricalEvidence({
  profile,
  requiredReturnPct,
  horizonDays,
}: {
  profile: RiskProfile;
  requiredReturnPct: number;
  horizonDays: number;
}) {
  const s = PROFILES[profile];
  const doubled = Math.round((s.reachedDoublePct / 100) * s.sessions);
  const goalAboveHistory = requiredReturnPct > s.bestPct;

  return (
    <Panel label="What history says" title={`The same rules across ${s.sessions} real 90-day windows`}>
      <p className="max-w-2xl text-[12.5px] leading-relaxed text-[var(--color-text-tertiary)]">
        {monthYearUtc(study.data.from)} – {monthYearUtc(study.data.to)}, {study.data.symbols.join(", ")} hourly candles from Binance, fees and
        slippage included. A new window starts every {study.method.stepDays} days, so good and bad stretches both count.
      </p>

      <div className="mt-5 grid grid-cols-2 gap-x-6 gap-y-5 sm:grid-cols-3">
        <Stat label="Windows in profit" value={`${s.positivePct}%`} />
        <Stat label="Typical (median)" value={signedPct(s.medianPct)} tone={tone(s.medianPct)} />
        <Stat label="1-in-10 bad case" value={signedPct(s.p10Pct)} tone={tone(s.p10Pct)} note="or worse, 1 window in 10" />
        <Stat label="1-in-10 good case" value={signedPct(s.p90Pct)} tone={tone(s.p90Pct)} note="or better, 1 window in 10" />
        <Stat label="Worst window" value={signedPct(s.worstPct)} tone={tone(s.worstPct)} />
        <Stat label="Kill switch hit" value={`${s.killSwitchPct}%`} note="of windows" />
      </div>

      <div className="mt-5 grid gap-3 border-t pt-5 sm:grid-cols-2" style={{ borderColor: "var(--hairline)" }}>
        <p className="text-[13px] leading-relaxed text-[var(--color-text-secondary)]">
          <span className="font-semibold text-[var(--color-text-primary)]">Versus buying and holding the same coins:</span> median{" "}
          {signedPct(study.buyHold.medianPct)}, but 1 window in 10 lost {Math.abs(study.buyHold.p10Pct).toFixed(1)}% or more. These rules typically
          earn less in exchange for a much smaller bad tail.
        </p>
        <p className="text-[13px] leading-relaxed text-[var(--color-text-secondary)]">
          <span className="font-semibold text-[var(--color-text-primary)]">Doubling the account:</span> {doubled} of {s.sessions} windows got there. The
          best window returned {signedPct(s.bestPct)}.
          {goalAboveHistory && ` Your goal needs +${requiredReturnPct.toFixed(0)}%, more than any window in this history.`}
        </p>
      </div>

      <p className="mt-4 text-[11.5px] leading-relaxed text-[var(--color-text-quaternary)]">
        Paper results on past data
        {horizonDays !== study.method.sessionDays ? `; your ${horizonDays}-day horizon differs from the ${study.method.sessionDays}-day windows measured here` : ""}.
        Markets change. This is a record, not a forecast, and not financial advice.
      </p>
    </Panel>
  );
}
